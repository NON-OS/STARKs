//! The statements this build verifies, each pinned by its program image,
//! periodic root and accepted parameter ids. Every value here is the one its
//! pinned proofs were made under (`spec/transfer`, `spec/not-before`, `spec/claim`, `spec/attest`,
//! `spec/activity`);
//! a verifier that finds them otherwise refuses with `Refusal::Image` or
//! `Refusal::Shape` before it reads a proof.

use crate::{Point, Shape, Statement};

/// The transfer circuit's columns: 34 of witness, 8 of permutation products,
/// the 2 mask columns at 42 and 43; degree 11, a two-row window, copy
/// challenges in F_p^2. The same for all three statements: they differ in
/// public words and wiring, not in columns.
const SHAPE: Shape = Shape {
    trace_width: 44,
    region_width: 34,
    window: 2,
    constraint_degree: 11,
    mask_pair: Some((42, 43)),
    challenge_lanes: 2,
};

/// Rate 1/64 over the minimal domain, every shipped point.
const EXTRA_BLOWUP_BITS: u32 = 5;

/// The longest proof accepted. Every pinned transfer and claim proof is below
/// 97,000 bytes and every attestation and activity proof below 116,000;
/// 128 KiB is above all of them and bounds what a gate reads.
const MAX_PROOF_BYTES: usize = 128 * 1024;

const fn point(params: [u8; 32], queries: usize, grind_bits: u32) -> Point {
    Point {
        params,
        queries,
        grind_bits,
    }
}

